# Edge cases
# ===================================================================


class TestEdgeCases:
    def test_optimize_empty_string_raises(self) -> None:
        with pytest.raises(SVGValidationError):
            optimize_svg("")

    def test_optimize_invalid_xml_raises(self) -> None:
        with pytest.raises(SVGValidationError):
            optimize_svg("<svg><unclosed>")

    def test_unknown_pass_raises(self) -> None:
        with pytest.raises(ValueError, match="Unknown pass"):
            optimize_svg(MINIMAL_SVG, passes=["nonexistent_pass"])

    def test_custom_pass_function(self) -> None:
        def uppercase(s: str) -> str:
            return s.upper()

        result = optimize_svg(MINIMAL_SVG, passes=[uppercase])
        assert "SVG" in result.svg

    def test_skip_validation(self) -> None:
        result = optimize_svg(MINIMAL_SVG, validate_input=False, validate_output=False)
        assert result.optimized_size > 0

    def test_svg_with_text_span(self) -> None:
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg">'
            '<text>hello <tspan font-weight="bold">world</tspan></text></svg>'
        )
        result = optimize_svg(svg)
        validate_svg(result.svg)
        assert "hello" in result.svg
        assert "world" in result.svg

    def test_svg_with_declarations(self) -> None:
        svg = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" '
            '"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n'
            '<svg xmlns="http://www.w3.org/2000/svg">'
            '<rect width="10" height="10"/></svg>'
        )
        result = optimize_svg(svg, validate_input=True)
        validate_svg(result.svg)

    def test_pass_registry_completeness(self) -> None:
        assert set(DEFAULT_PASSES) == set(PASS_REGISTRY.keys())
        assert len(PASS_REGISTRY) == 10

    def test_namespace_handling_without_ns(self) -> None:
        svg = "<svg><rect width='10' height='10'/></svg>"
        result = optimize_svg(svg)
        validate_svg(result.svg)
