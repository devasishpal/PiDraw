class TestRemoveComments:
    def test_removes_single_comment(self) -> None:
        result = optimize_svg(SVG_WITH_COMMENTS, passes=["remove_comments"])
        assert "<!--" not in result.svg
        assert "comment" not in result.svg

    def test_does_not_remove_text_content(self) -> None:
        svg = '<svg xmlns="http://www.w3.org/2000/svg"><text>&lt;!-- not a comment --></text></svg>'
        result = optimize_svg(svg, passes=["remove_comments"])
        assert "text" in result.svg

    def test_svg_still_valid(self) -> None:
        result = optimize_svg(SVG_WITH_COMMENTS, passes=["remove_comments"])
        validate_svg(result.svg)

    def test_removes_multiline_comments(self) -> None:
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg">'
            "<!--\nmulti\nline\n-->"
            '<rect width="10" height="10"/></svg>'
        )
        result = optimize_svg(svg, passes=["remove_comments"])
        assert "<!--" not in result.svg
        assert "multi" not in result.svg


