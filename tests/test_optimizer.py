class TestValidation:
    def test_valid_minimal_svg(self) -> None:
        assert validate_svg(MINIMAL_SVG) is True

    def test_empty_string_raises(self) -> None:
        with pytest.raises(SVGValidationError, match="empty"):
            validate_svg("")

    def test_whitespace_only_raises(self) -> None:
        with pytest.raises(SVGValidationError, match="empty"):
            validate_svg("   \n  ")

    def test_no_svg_root_raises(self) -> None:
        with pytest.raises(SVGValidationError, match="<svg>"):
            validate_svg("<div></div>")

    def test_malformed_xml_raises(self) -> None:
        with pytest.raises(SVGValidationError, match="XML parsing"):
            validate_svg("<svg><unclosed>")

    def test_svg_with_declaration(self) -> None:
        svg = '<?xml version="1.0"?>\n<svg xmlns="http://www.w3.org/2000/svg"/>'
        assert validate_svg(svg) is True


